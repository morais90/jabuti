use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

use jabuti_core::authorship::{self, Origin};
use rstest::rstest;

const WRITTEN: &str = "pub fn shown() -> u8 {\n    1\n}\n";

fn origin_of(path: &str, source: &str) -> Option<Origin> {
    authorship::origin(Path::new(path), source, &BTreeSet::new())
}

#[rstest]
#[case::vendor("vendor/serde/src/lib.rs")]
#[case::third_party("third_party/zlib/inflate.ts")]
#[case::hyphenated("libs/third-party/chart.ts")]
#[case::node_modules("web/node_modules/left-pad/index.ts")]
#[case::capitalised("Libs/ThirdParty/chart.ts")]
fn a_file_under_a_vendored_directory_is_vendored(#[case] path: &str) {
    assert_eq!(origin_of(path, WRITTEN), Some(Origin::Vendored));
}

#[rstest]
#[case::directory("ui/src/api/generated/core/auth.ts")]
#[case::dunder("src/__generated__/schema.kt")]
#[case::gen_suffix("ui/src/api/types.gen.ts")]
#[case::generated_suffix("app/Routes.generated.kt")]
#[case::capitalised("app/Generated/Routes.kt")]
fn a_file_named_or_placed_as_generated_is_generated(#[case] path: &str) {
    assert_eq!(origin_of(path, WRITTEN), Some(Origin::Generated));
}

#[rstest]
#[case::hey_api("// This file is auto-generated by @hey-api/openapi-ts\n\nexport type A = 1;\n")]
#[case::openapi_generator(
    "/*\n * Machines API\n *\n * The version of the OpenAPI document: 2.0.0\n *\n * Generated by: https://openapi-generator.tech\n */\n\nuse super::configuration;\n"
)]
#[case::prost("// This file is @generated by prost-build.\npub struct Message {}\n")]
#[case::go_style("// Code generated by sqlc. DO NOT EDIT.\nexport const query = 1;\n")]
#[case::after_a_shebang("#!/usr/bin/env node\n// This file was generated by the build.\nmain();\n")]
#[case::after_a_file_annotation(
    "@file:Suppress(\"unused\")\n// Generated code, DO NOT EDIT.\npackage app\n"
)]
#[case::after_use_strict(
    "\"use strict\";\n// This file is generated by the schema build.\nexport {};\n"
)]
#[case::block_after_blank_lines("\n\n/**\n * AUTOGENERATED, edits are lost.\n */\nfun main() {}\n")]
fn a_header_that_says_the_file_is_generated_marks_it_generated(#[case] source: &str) {
    assert_eq!(origin_of("src/client.rs", source), Some(Origin::Generated));
}

#[rstest]
#[case::marker_after_the_code("pub fn shown() {}\n// This file is auto-generated by nothing.\n")]
#[case::a_doc_comment_about_something_else(
    "//! Wraps the client the server publishes.\n\npub fn shown() {}\n"
)]
#[case::a_warning_that_is_not_about_generation(
    "// Do not edit these defaults without updating the configuration guide.\nexport const limit = 3;\n"
)]
#[case::a_marker_too_deep_in_the_header(&format!("{}// @generated\n", "// line\n".repeat(40)))]
fn a_file_written_by_hand_has_no_origin(#[case] source: &str) {
    assert_eq!(origin_of("src/client.rs", source), None);
}

#[test]
fn only_the_directories_of_a_path_place_it_and_not_its_own_name() {
    assert_eq!(
        [
            origin_of("src/vendor.rs", WRITTEN),
            origin_of("src/generated.ts", WRITTEN),
        ],
        [None, None]
    );
}

fn paths(listed: &[&str]) -> Vec<PathBuf> {
    listed.iter().map(PathBuf::from).collect()
}

fn translations_among(listed: &[&str]) -> Vec<String> {
    let paths = paths(listed);

    authorship::translations(paths.iter().map(PathBuf::as_path))
        .into_iter()
        .map(|path| path.display().to_string())
        .collect()
}

#[test]
fn a_set_of_locale_files_in_a_translations_directory_is_translations() {
    assert_eq!(
        translations_among(&[
            "ui/src/i18n/config.ts",
            "ui/src/i18n/en.ts",
            "ui/src/i18n/i18next.d.ts",
            "ui/src/i18n/pt-BR.ts",
            "app/Locales/zh-Hans.kt",
            "app/Locales/sr_Latn_RS.kt",
            "app/Locales/es-419.kt",
            "web/l10n/en-us.ts",
            "web/l10n/pt-br.ts",
        ]),
        [
            "app/Locales/es-419.kt",
            "app/Locales/sr_Latn_RS.kt",
            "app/Locales/zh-Hans.kt",
            "ui/src/i18n/en.ts",
            "ui/src/i18n/pt-BR.ts",
            "web/l10n/en-us.ts",
            "web/l10n/pt-br.ts",
        ]
    );
}

#[test]
fn a_lone_file_named_like_a_locale_is_code() {
    assert_eq!(
        translations_among(&[
            "slides/i18n/portuguese.rs",
            "slides/i18n/tr.rs",
            "web/i18n/en.ts",
            "web/i18n/pt.rs",
        ]),
        Vec::<String>::new()
    );
}

#[test]
fn locale_files_outside_a_translations_directory_are_code() {
    assert_eq!(
        translations_among(&[
            "src/en.ts",
            "src/it.ts",
            "src/i18n/EN.ts",
            "src/i18n/pt-br.ts"
        ]),
        Vec::<String>::new()
    );
}

#[test]
fn a_name_whose_second_part_is_no_region_area_or_script_is_code() {
    let names = ["x", "12", "1234", "Abcde", "abcd"]
        .into_iter()
        .flat_map(|part| ["en", "pt"].map(|language| format!("src/i18n/{language}-{part}.ts")))
        .collect::<Vec<_>>();
    let listed: Vec<&str> = names.iter().map(String::as_str).collect();

    assert_eq!(translations_among(&listed), Vec::<String>::new());
}

#[test]
fn a_translation_is_told_apart_only_when_its_set_names_it() {
    let set = BTreeSet::from([PathBuf::from("ui/src/i18n/en.ts")]);

    assert_eq!(
        [
            authorship::origin(Path::new("ui/src/i18n/en.ts"), WRITTEN, &set),
            authorship::origin(Path::new("ui/src/i18n/config.ts"), WRITTEN, &set),
        ],
        [Some(Origin::Translation), None]
    );
}

#[test]
fn each_origin_publishes_the_id_its_report_uses() {
    assert_eq!(
        Origin::ALL.map(Origin::id),
        ["generated", "vendored", "translation"]
    );
}

#[test]
fn a_code_directory_with_short_file_names_holds_no_translations() {
    assert_eq!(
        translations_among(&[
            "src/lang/en.rs",
            "src/lang/pt.rs",
            "src/i18n/mod.rs",
            "src/i18n/ast.rs",
            "tools/locales/ts.ts",
            "tools/locales/kt.ts",
        ]),
        Vec::<String>::new()
    );
}

#[test]
fn a_place_is_enough_to_leave_a_file_out_before_it_is_read() {
    let set = BTreeSet::from([PathBuf::from("ui/i18n/en.ts")]);

    assert_eq!(
        [
            authorship::placed(Path::new("vendor/zlib/inflate.rs"), &set),
            authorship::placed(Path::new("api/types.gen.ts"), &set),
            authorship::placed(Path::new("ui/i18n/en.ts"), &set),
            authorship::placed(Path::new("src/client.rs"), &set),
        ],
        [
            Some(Origin::Vendored),
            Some(Origin::Generated),
            Some(Origin::Translation),
            None,
        ]
    );
}

#[test]
fn a_generated_header_outranks_a_translation_place() {
    let set = BTreeSet::from([PathBuf::from("ui/i18n/en.ts")]);

    assert_eq!(
        authorship::origin(
            Path::new("ui/i18n/en.ts"),
            "// @generated\nexport {};\n",
            &set
        ),
        Some(Origin::Generated)
    );
}

#[test]
fn a_directory_is_named_for_translations_whatever_its_case() {
    assert_eq!(
        [
            "ui/i18n",
            "app/Locales",
            "web/L10N",
            "src/lang",
            "src/messages"
        ]
        .map(|directory| authorship::holds_translations(Path::new(directory))),
        [true, true, true, false, false]
    );
}

#[test]
fn a_vendored_file_stays_vendored_whatever_its_header_says() {
    assert_eq!(
        origin_of(
            "vendor/client/api.rs",
            "// @generated by the upstream build\npub fn a() {}\n"
        ),
        Some(Origin::Vendored)
    );
}
