pub fn origin(path: &Path, source: &str, translations: &BTreeSet<PathBuf>) -> Option<Origin> {
    let placed = placed(path, translations);
    match placed {
        Some(Origin::Vendored | Origin::Generated) => placed,
        _ if generated_by_header(source) => Some(Origin::Generated),
        _ => placed,
    }
}

pub fn placed(path: &Path, translations: &BTreeSet<PathBuf>) -> Option<Origin> {
    if directories(path).any(|name| VENDORED.contains(&name.as_str())) {
        return Some(Origin::Vendored);
    }
    if generated_by_place(path) {
        return Some(Origin::Generated);
    }

    translations.contains(path).then_some(Origin::Translation)
}

pub fn holds_translations(directory: &Path) -> bool {
    directory
        .file_name()
        .and_then(|name| name.to_str())
        .is_some_and(|name| TRANSLATION_DIRECTORIES.contains(&name.to_lowercase().as_str()))
}

pub fn translations<'a>(paths: impl IntoIterator<Item = &'a Path>) -> BTreeSet<PathBuf> {
    let mut sets: BTreeMap<(&Path, Option<&str>), Vec<&Path>> = BTreeMap::new();
    for path in paths {
        let parent = path.parent().unwrap_or(Path::new(""));
        let named_for_a_locale = path
            .file_stem()
            .and_then(|stem| stem.to_str())
            .is_some_and(is_locale);
        if holds_translations(parent) && named_for_a_locale {
            let extension = path.extension().and_then(|extension| extension.to_str());
            sets.entry((parent, extension)).or_default().push(path);
        }
    }

    sets.into_values()
        .filter(|set| set.len() > 1)
        .flatten()
        .map(Path::to_path_buf)
        .collect()
}

fn directories(path: &Path) -> impl Iterator<Item = String> {
    path.parent()
        .into_iter()
        .flat_map(Path::components)
        .filter_map(|component| component.as_os_str().to_str())
        .map(str::to_lowercase)
}

fn generated_by_place(path: &Path) -> bool {
    let in_directory = directories(path).any(|name| GENERATED_DIRECTORIES.contains(&name.as_str()));
    let named = path
        .file_stem()
        .and_then(|stem| stem.to_str())
        .map(str::to_lowercase)
        .is_some_and(|stem| {
            GENERATED_SUFFIXES
                .iter()
                .any(|suffix| stem.ends_with(suffix))
        });

    in_directory || named
}

fn generated_by_header(source: &str) -> bool {
    let header: String = source
        .lines()
        .take(HEADER_LINES)
        .map(str::trim)
        .filter(|line| {
            !line.is_empty()
                && !DIRECTIVES
                    .iter()
                    .any(|directive| line.starts_with(directive))
        })
        .take_while(|line| {
            ["//", "/*", "*"]
                .iter()
                .any(|opening| line.starts_with(opening))
        })
        .map(str::to_lowercase)
        .collect::<Vec<_>>()
        .join("\n");
    let warned = header.contains("do not edit") && header.contains("generated");

    warned
        || GENERATED_MARKERS
            .iter()
            .any(|marker| header.contains(marker))
}

fn is_locale(stem: &str) -> bool {
    let mut parts = stem.split(['-', '_']);
    let language = parts.next().unwrap_or_default();
    let rest: Vec<&str> = parts.collect();

    LANGUAGES.contains(&language) && rest.len() <= 2 && rest.iter().all(|part| is_subtag(part))
}

fn is_subtag(part: &str) -> bool {
    let region = part.len() == 2 && part.chars().all(|letter| letter.is_ascii_alphabetic());
    let area = part.len() == 3 && part.chars().all(|digit| digit.is_ascii_digit());
    let script = part.len() == 4
        && part
            .chars()
            .next()
            .is_some_and(|first| first.is_ascii_uppercase())
        && part
            .chars()
            .skip(1)
            .all(|letter| letter.is_ascii_lowercase());

    region || area || script
}
